// Bundle lib/finance into functions/engine.cjs (CommonJS, date-fns included),
// so Cloud Functions and Node scripts run the same money rules as the app.
// Runs automatically before deploying functions (firebase.json predeploy),
// before `npm run dev:local` and before seeding.
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
await build({
  entryPoints: [path.join(root, "lib/finance/server.js")],
  outfile: path.join(root, "functions/engine.cjs"),
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  banner: { js: "// GENERATED by scripts/build-functions-engine.mjs from lib/finance — do not edit." },
  logLevel: "warning",
});
console.log("functions/engine.cjs built from lib/finance");
