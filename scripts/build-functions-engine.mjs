// Bundle lib/finance into functions/engine.cjs, lib/notify into
// functions/notify.cjs and lib/audit/actor into functions/audit.cjs (CommonJS, date-fns included),
// so Cloud Functions and Node scripts run the same money rules as the app.
// Runs automatically before deploying functions (firebase.json predeploy),
// before `npm run dev:local` and before seeding.
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// "@/lib/..." as in the app
const appAlias = {
  name: "app-alias",
  setup(b) {
    b.onResolve({ filter: /^@\// }, async (args) => b.resolve(`./${args.path.slice(2)}`, { resolveDir: root, kind: args.kind }));
  },
};
const common = { bundle: true, platform: "node", format: "cjs", target: "node20", logLevel: "warning", plugins: [appAlias] };
await build({
  ...common,
  entryPoints: [path.join(root, "lib/finance/server.js")],
  outfile: path.join(root, "functions/engine.cjs"),
  banner: { js: "// GENERATED by scripts/build-functions-engine.mjs from lib/finance — do not edit." },
});
await build({
  ...common,
  entryPoints: [path.join(root, "lib/notify/server.js")],
  outfile: path.join(root, "functions/notify.cjs"),
  banner: { js: "// GENERATED by scripts/build-functions-engine.mjs from lib/notify — do not edit." },
});
await build({
  ...common,
  entryPoints: [path.join(root, "lib/audit/actor.js")],
  outfile: path.join(root, "functions/audit.cjs"),
  banner: { js: "// GENERATED by scripts/build-functions-engine.mjs from lib/audit — do not edit." },
});
console.log("functions/engine.cjs, notify.cjs and audit.cjs built from lib/finance, lib/notify and lib/audit");
